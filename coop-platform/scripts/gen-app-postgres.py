"""Generate the PostgreSQL version of the app's own tables (ecis_*) and of the limited user's grants from the live MySQL schema.

Usage: python -I gen-app-postgres.py            (reads the MySQL root password from ../../db.txt at run time)
Writes database/postgres/migrations:
  V009__app_tables.sql        drops the old stale copies, creates every ecis_ table with keys and indexes (schema legacy)
  V010__app_foreign_keys.sql  foreign keys between ecis_ tables (apply after the data is loaded)
  V011__app_grants.sql        what MySQL lets coop_app do, written as PostgreSQL grants
(sequences are set by the hand-written V014 after the load)
The data itself is copied with scripts/load-legacy-to-postgres.py (it works for ecis_ tables too).
Everything lives in schema `legacy`, as in MySQL where the app's tables sit beside the old ones; the connection uses currentSchema=legacy.
Names are lowercased (the ecis_ names already are).
"""
import os, re, sys, collections, pymysql

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.abspath(os.path.join(HERE, "..", ".."))
OUT = os.path.join(HERE, "..", "database", "postgres", "migrations")
SCHEMA = "iaccsbsucmpc01"
cfg = {}
for line in open(os.path.join(ROOT, "db.txt")):
    if ":" in line:
        k, v = line.split(":", 1)
        cfg[k.strip()] = v.strip()
db = pymysql.connect(host="127.0.0.1", port=3311, user="root", password=cfg["password"], database=SCHEMA, charset="utf8mb4")
cur = db.cursor()


def q(sql, *a):
    cur.execute(sql, a)
    return cur.fetchall()


def ident(n):
    return '"' + n.lower() + '"'


def pg_type(col_type, data_type, extra):
    t = col_type.lower()
    unsigned = "unsigned" in t
    if data_type == "tinyint":
        return "smallint"
    if data_type == "smallint":
        return "integer" if unsigned else "smallint"
    if data_type in ("mediumint", "int", "integer"):
        return "bigint" if unsigned else "integer"
    if data_type == "bigint":
        return "bigint"  # ids; unsigned values here stay far below the signed limit and must match the columns that reference them
    if data_type in ("decimal", "numeric"):
        m = re.search(r"\((\d+),(\d+)\)", t)
        return "numeric(%s,%s)" % m.groups() if m else "numeric"
    if data_type == "double":
        return "double precision"
    if data_type == "float":
        return "real"
    if data_type in ("datetime", "timestamp"):
        return "timestamp"
    if data_type == "date":
        return "date"
    if data_type == "time":
        return "time"
    if data_type == "year":
        return "smallint"
    if data_type in ("varchar", "char"):
        m = re.search(r"\((\d+)\)", t)
        return "varchar(%s)" % m.group(1)
    if data_type in ("text", "tinytext", "mediumtext", "longtext", "enum", "set"):
        return "text" if data_type != "enum" else "varchar(64)"
    if data_type in ("blob", "tinyblob", "mediumblob", "longblob", "varbinary", "binary"):
        return "bytea"
    raise ValueError("no type for " + col_type)


def pg_default(default, data_type, pgt):
    if default is None:
        return None
    d = default
    if d.upper().startswith("CURRENT_TIMESTAMP"):
        return "CURRENT_TIMESTAMP"
    if pgt.startswith(("smallint", "integer", "bigint", "numeric", "double", "real")):
        return d
    if data_type in ("date", "datetime", "timestamp") and d.startswith("0000"):
        return None
    return "'" + d.replace("'", "''") + "'"


tables = [r[0] for r in q("select table_name from information_schema.tables where table_schema=%s and table_type='BASE TABLE' and table_name like 'ecis\\_%%' order by 1", SCHEMA)]
ddl = ["-- Generated by scripts/gen-app-postgres.py from the live MySQL schema. Do not edit by hand; regenerate.",
       "-- The app's own tables, in schema legacy beside the old ones (as in MySQL). Types: tinyint -> smallint, datetime -> timestamp,",
       "-- enum -> varchar, AUTO_INCREMENT -> identity.", "SET search_path = legacy;", ""]
for t in tables:
    ddl.append("DROP TABLE IF EXISTS %s CASCADE;" % ident(t))
ddl.append("")
onupdate = []
identity = []
for t in tables:
    cols = q("select column_name,column_type,data_type,is_nullable,column_default,extra from information_schema.columns where table_schema=%s and table_name=%s order by ordinal_position", SCHEMA, t)
    pk = [r[0] for r in q("select column_name from information_schema.key_column_usage where table_schema=%s and table_name=%s and constraint_name='PRIMARY' order by ordinal_position", SCHEMA, t)]
    lines = []
    for name, ctype, dtype, nullable, default, extra in cols:
        pgt = pg_type(ctype, dtype, extra)
        parts = [ident(name), pgt]
        ex = (extra or "").lower()
        if "auto_increment" in ex:
            parts[1] = "bigint" if pgt.startswith("numeric") else pgt
            parts.append("GENERATED BY DEFAULT AS IDENTITY")
            identity.append((t, name))
        else:
            d = pg_default(default, dtype, pgt)
            if d is not None:
                parts.append("DEFAULT " + d)
        if nullable == "NO":
            parts.append("NOT NULL")
        if dtype == "enum":
            vals = re.findall(r"'((?:[^']|'')*)'", ctype)
            parts.append("CHECK (%s IN (%s))" % (ident(name), ",".join("'%s'" % v for v in vals)))
        if "on update" in ex:
            onupdate.append((t, name))
        lines.append("    " + " ".join(parts))
    if pk:
        lines.append("    PRIMARY KEY (%s)" % ", ".join(ident(c) for c in pk))
    ddl.append("CREATE TABLE %s (\n%s\n);" % (ident(t), ",\n".join(lines)))
    # secondary indexes and unique keys
    idx = collections.OrderedDict()
    for name, nonuni, seq, col, sub in q("select index_name,non_unique,seq_in_index,column_name,sub_part from information_schema.statistics where table_schema=%s and table_name=%s and index_name<>'PRIMARY' order by index_name,seq_in_index", SCHEMA, t):
        idx.setdefault((name, nonuni), []).append(col)
    for (name, nonuni), cs in idx.items():
        iname = ("%s_%s" % (t, name))[:63].lower()
        ddl.append("CREATE %sINDEX %s ON %s (%s);" % ("" if nonuni else "UNIQUE ", ident(iname), ident(t), ", ".join(ident(c) for c in cs)))
    ddl.append("")

if onupdate:
    raise SystemExit("ON UPDATE CURRENT_TIMESTAMP columns found: add a trigger for %s" % onupdate)
open(os.path.join(OUT, "V009__app_tables.sql"), "w", newline="\n").write("\n".join(ddl) + "\n")

# foreign keys between ecis_ tables
fk = ["-- Generated by scripts/gen-app-postgres.py. Apply after the data of the ecis_ tables is loaded.", "SET search_path = legacy;", ""]
rows = q("""select k.constraint_name,k.table_name,k.referenced_table_name,rc.delete_rule,rc.update_rule,
            group_concat(k.column_name order by k.ordinal_position),group_concat(k.referenced_column_name order by k.ordinal_position)
            from information_schema.key_column_usage k join information_schema.referential_constraints rc
              on rc.constraint_schema=k.constraint_schema and rc.constraint_name=k.constraint_name and rc.table_name=k.table_name
            where k.table_schema=%s and k.table_name like 'ecis\\_%%' and k.referenced_table_name is not null
            group by k.constraint_name,k.table_name,k.referenced_table_name,rc.delete_rule,rc.update_rule order by k.table_name,k.constraint_name""", SCHEMA)
for name, t, rt, dr, ur, cs, rcs in rows:
    if not rt.startswith("ecis_"):
        fk.append("-- skipped (points at an old table): %s %s -> %s" % (t, name, rt))
        continue
    fk.append("ALTER TABLE %s ADD CONSTRAINT %s FOREIGN KEY (%s) REFERENCES %s (%s) ON DELETE %s ON UPDATE %s;" % (
        ident(t), ident(("%s_%s" % (t, name))[:63]), ", ".join(ident(c) for c in cs.split(",")), ident(rt), ", ".join(ident(c) for c in rcs.split(",")), dr, ur))
open(os.path.join(OUT, "V010__app_foreign_keys.sql"), "w", newline="\n").write("\n".join(fk) + "\n")

# grants
g = ["-- Generated by scripts/gen-app-postgres.py from SHOW GRANTS of the MySQL application user, for the PostgreSQL role coop_app.",
     "SET search_path = legacy;", "GRANT USAGE ON SCHEMA legacy TO coop_app;", "REVOKE ALL ON ALL TABLES IN SCHEMA legacy FROM coop_app;", "GRANT SELECT ON ALL TABLES IN SCHEMA legacy TO coop_app;",
     "ALTER DEFAULT PRIVILEGES FOR ROLE coop_admin IN SCHEMA legacy GRANT SELECT ON TABLES TO coop_app;"]
# MySQL has one account per host (coop_app@% and coop_app@localhost); a local connection uses the most specific one, so take every grant of both.
hosts = [r[0] for r in q("select host from mysql.user where user=%s", cfg["app_user"])]
seen = set()
for host in hosts:
    cur.execute("show grants for '%s'@'%s'" % (cfg["app_user"], host))
    for (row,) in cur.fetchall():
        m = re.match(r"GRANT (.+?) ON `([^`]+)`\.`([^`]+)` TO", row)
        if not m or m.group(2) != SCHEMA:
            continue
        privs, _, table = m.groups()
        table = table.lower()
        # SHOW GRANTS lists each privilege with its own columns when it is a column grant: "INSERT, UPDATE (a, b)" is INSERT on the whole table and UPDATE on a and b only
        whole, by_column = [], []
        for part in re.findall(r"([A-Z ]+?)(?: \(([^)]*)\))?(?:, |$)", privs):
            name, cols = part[0].strip(), part[1]
            if cols:
                by_column.append("%s (%s)" % (name, ", ".join(ident(c.strip()) for c in cols.split(","))))
            elif name:
                whole.append(name)
        stmts = []
        if whole:
            stmts.append("GRANT %s ON %s TO coop_app;" % (", ".join(whole), ident(table)))
        if by_column:
            stmts.append("GRANT %s ON %s TO coop_app;" % (", ".join(by_column), ident(table)))
        for stmt in stmts:
            if stmt not in seen:
                seen.add(stmt)
                g.append(stmt)
# an INSERT needs the table's own sequence (PostgreSQL keeps them apart)
g.append("GRANT USAGE, SELECT ON ALL SEQUENCES IN SCHEMA legacy TO coop_app;")
g.append("ALTER DEFAULT PRIVILEGES FOR ROLE coop_admin IN SCHEMA legacy GRANT USAGE, SELECT ON SEQUENCES TO coop_app;")
open(os.path.join(OUT, "V011__app_grants.sql"), "w", newline="\n").write("\n".join(g) + "\n")
print(len(tables), "tables;", len(identity), "identity columns;", len(onupdate), "on-update columns;", len(seen), "grants")
