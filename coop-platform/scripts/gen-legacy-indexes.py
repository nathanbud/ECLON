"""Generate PostgreSQL scripts for the keys, indexes and foreign keys of the legacy MySQL schema.

Usage: MYSQL_PWD=<coop_app password> python -I gen-legacy-indexes.py <output dir>
Writes V006__legacy_primary_keys_and_indexes.sql and V007__legacy_foreign_keys.sql.
Foreign keys are added NOT VALID (old data may hold orphans); VALIDATE them separately.
"""
import os, sys, hashlib, collections, pymysql
out = sys.argv[1]
db = pymysql.connect(host="127.0.0.1", port=3311, user="coop_app", password=os.environ["MYSQL_PWD"], database="iaccsbsucmpc01")
cur = db.cursor()
def nm(s):
    return s if len(s) <= 63 else s[:54] + "_" + hashlib.md5(s.encode()).hexdigest()[:8]
def q(c): return '"%s"' % c.lower() if not c[0].isdigit() else '"%s"' % c
cur.execute("select table_name from information_schema.tables where table_schema='iaccsbsucmpc01' and table_type='BASE TABLE' and table_name <> 'bsucmpc_client_financial_snapshot_hourly'")
tables = {t.lower() for (t,) in cur.fetchall()}
cur.execute("select table_name,index_name,non_unique,seq_in_index,column_name,index_type from information_schema.statistics where table_schema='iaccsbsucmpc01' order by table_name,index_name,seq_in_index")
idx = collections.OrderedDict()
for t, i, nu, seq, c, ty in cur.fetchall():
    if t.lower() not in tables or ty == "FULLTEXT": continue
    idx.setdefault((t.lower(), i), {"nu": nu, "cols": []})["cols"].append(c)
lines = ["-- Generated by scripts/gen-legacy-indexes.py from the MySQL schema. Keys first, then plain indexes.", ""]
seen = set()
for (t, i), d in idx.items():
    cols = ", ".join(q(c) for c in d["cols"])
    if i == "PRIMARY":
        lines.append('ALTER TABLE legacy."%s" ADD CONSTRAINT %s PRIMARY KEY (%s);' % (t, nm("pk_" + t), cols))
for (t, i), d in idx.items():
    if i == "PRIMARY": continue
    cols = ", ".join(q(c) for c in d["cols"])
    key = (t, cols)
    if key in seen: continue   # same columns already indexed
    seen.add(key)
    name = nm(("uq_" if not d["nu"] else "ix_") + t + "_" + i.lower())
    lines.append('CREATE %sINDEX IF NOT EXISTS %s ON legacy."%s" (%s);' % ("" if d["nu"] else "UNIQUE ", name, t, cols))
open(os.path.join(out, "V006__legacy_primary_keys_and_indexes.sql"), "w").write("\n".join(lines) + "\n")
cur.execute("""select k.constraint_name,k.table_name,k.column_name,k.referenced_table_name,k.referenced_column_name
 from information_schema.key_column_usage k where k.table_schema='iaccsbsucmpc01' and k.referenced_table_name is not null order by k.constraint_name,k.ordinal_position""")
fk = collections.OrderedDict()
for n, t, c, rt, rc in cur.fetchall():
    fk.setdefault((n, t.lower(), rt.lower()), []).append((c, rc))
l2 = ["-- Generated by scripts/gen-legacy-indexes.py. NOT VALID: existing rows are not checked; run VALIDATE CONSTRAINT per table.", "",
      "-- The loader made these numeric where the referenced key is bigint; PostgreSQL needs equal types for a foreign key."]
for t, c in [("ecis_journal", "reverses_id"), ("ecis_journal_line", "journal_id"), ("onlinetransdt", "onlineid"),
             ("onlinetransdta", "onlineid"), ("onlinetransdth", "onlineid")]:
    l2.append('ALTER TABLE legacy."%s" ALTER COLUMN "%s" TYPE bigint;' % (t, c))
l2.append("")
# PostgreSQL needs the referenced columns to be exactly a primary key or unique index. MySQL does not, so those links stay soft.
uniq = collections.defaultdict(set)
for (t, i), d in idx.items():
    if i == "PRIMARY" or not d["nu"]: uniq[t].add(frozenset(c.lower() for c in d["cols"]))
skipped = []
for (n, t, rt), cs in fk.items():
    if t not in tables or rt not in tables: continue
    if frozenset(r.lower() for _, r in cs) not in uniq[rt]:
        skipped.append("-- skipped (%s.%s -> %s (%s) is not unique): %s" % (t, ", ".join(c for c, _ in cs), rt, ", ".join(r for _, r in cs), n))
        continue
    l2.append('ALTER TABLE legacy."%s" ADD CONSTRAINT %s FOREIGN KEY (%s) REFERENCES legacy."%s" (%s) NOT VALID;' %
              (t, nm("fk_" + t + "_" + n.lower()), ", ".join(q(c) for c, _ in cs), rt, ", ".join(q(r) for _, r in cs)))
l2 += [""] + skipped
open(os.path.join(out, "V007__legacy_foreign_keys.sql"), "w").write("\n".join(l2) + "\n")
print(len(idx), "indexes,", len(fk), "foreign keys")
