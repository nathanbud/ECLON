-- Year-end closing of the books (Accounting > Year-end close). An accountant prepares the closing of a finished year; a different person posts it.
-- Posting writes the old system's computer-generated Closing Entry (transsum module 1, type 99, dated 31 December): every income (4xxxx) and expense (5xxxx)
-- account is brought to zero per department and the difference goes to 30198 Undivided net surplus. One row here per attempt; at most one that is not cancelled
-- per branch and year. The fingerprint is a SHA-256 of the closing lines when prepared; posting refuses if the ledger has changed since.
-- UPDATE on ecis_gl_year_balance lets the posting add the closing lines to a year whose balances were already built.
-- The MySQL copy is V060. Apply with scripts/migrate-postgres.ps1.
CREATE TABLE legacy.ecis_year_end_close (
    id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    branch_code integer       NOT NULL,
    tr_year     integer       NOT NULL,
    status      varchar(12)   NOT NULL,
    surplus     numeric(17,2) NOT NULL,
    line_count  integer       NOT NULL,
    fingerprint varchar(64)   NOT NULL,
    prepared_by varchar(60)   NOT NULL,
    prepared_at timestamp     NOT NULL,
    decided_by  varchar(60),
    decided_at  timestamp,
    reason      varchar(500),
    tr_ctlno    bigint,
    CONSTRAINT ecis_year_end_close_status CHECK (status IN ('PREPARED', 'POSTED', 'CANCELLED'))
);
CREATE UNIQUE INDEX ecis_year_end_close_one ON legacy.ecis_year_end_close (branch_code, tr_year) WHERE status <> 'CANCELLED';
GRANT SELECT, INSERT, UPDATE ON legacy.ecis_year_end_close TO coop_app;
GRANT UPDATE ON legacy.ecis_gl_year_balance TO coop_app;
