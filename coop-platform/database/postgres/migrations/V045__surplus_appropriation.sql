-- Appropriation of the net surplus (Accounting > Dividends > Appropriation, AppropriationController): after a year is closed, the net surplus the closing put in
-- the undivided net surplus account is set aside to the statutory funds (RA 9520 Article 86: reserve, education and training, community development, optional)
-- and allocated to interest on share capital and patronage refund, as the general assembly resolved. DRAFT, FOR_REVIEW, APPROVED, POSTED (or CANCELLED); maker,
-- approver and poster are three different people; posting writes one General Journal through the ledger. One live appropriation per branch and year.
-- The cooperative's registration date (its first five years need a larger reserve fund) is the setting organization.registered_on in ecis_setting.
-- The MySQL copy is V082. Applied with scripts/migrate-postgres.ps1, or from the application (Apply them now).
CREATE TABLE legacy.ecis_appropriation (
    id               bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    branch_code      integer       NOT NULL,
    year             integer       NOT NULL,
    reference        varchar(20),
    entry_date       date          NOT NULL,
    resolution       varchar(200)  NOT NULL,
    net_surplus      numeric(18,2) NOT NULL,
    status           varchar(12)   NOT NULL,
    created_by       varchar(60)   NOT NULL,
    created_at       timestamp(3)  NOT NULL,
    submitted_at     timestamp(3),
    approved_by      varchar(60),
    approved_at      timestamp(3),
    posted_by        varchar(60),
    posted_at        timestamp(3),
    tr_year          integer,
    tr_ctlno         bigint,
    cancel_reason    varchar(200),
    CONSTRAINT ecis_appropriation_status CHECK (status IN ('DRAFT', 'FOR_REVIEW', 'APPROVED', 'POSTED', 'CANCELLED'))
);
CREATE UNIQUE INDEX ecis_appropriation_live ON legacy.ecis_appropriation (branch_code, year) WHERE status IN ('DRAFT', 'FOR_REVIEW', 'APPROVED', 'POSTED');
CREATE TABLE legacy.ecis_appropriation_line (
    appropriation_id bigint        NOT NULL REFERENCES legacy.ecis_appropriation (id),
    line_no          integer       NOT NULL,
    kind             varchar(12)   NOT NULL,
    name             varchar(80)   NOT NULL,
    percent          numeric(7,4),
    amount           numeric(18,2) NOT NULL,
    account_code     varchar(20),
    PRIMARY KEY (appropriation_id, line_no),
    CONSTRAINT ecis_appropriation_line_kind CHECK (kind IN ('RESERVE', 'EDUCATION', 'COMMUNITY', 'OPTIONAL', 'OTHER', 'ISC', 'PR'))
);
GRANT SELECT, INSERT, UPDATE ON legacy.ecis_appropriation TO coop_app;
GRANT SELECT, INSERT, DELETE ON legacy.ecis_appropriation_line TO coop_app;
