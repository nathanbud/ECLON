-- Opening balances (Accounting > Opening balances, OpeningBalanceController): a new cooperative's balances on the day it starts on this system, entered or
-- imported as a batch of lines: general ledger accounts (cash, banks, fixed assets, payables, equity ...) and members' savings and share capital accounts,
-- whose totals go to their control accounts. A batch goes DRAFT, FOR_REVIEW, APPROVED, POSTED (or CANCELLED); maker, approver and poster are three different
-- people. Posting writes one General Journal through the ledger; the lines here are never changed after that. The MySQL copy is V081.
-- Applied with scripts/migrate-postgres.ps1, or from the application (Apply them now).
CREATE TABLE legacy.ecis_opening_batch (
    id            bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    branch_code   integer      NOT NULL,
    reference     varchar(20),
    opening_date  date         NOT NULL,
    description   varchar(200) NOT NULL,
    status        varchar(12)  NOT NULL,
    created_by    varchar(60)  NOT NULL,
    created_at    timestamp(3) NOT NULL,
    submitted_at  timestamp(3),
    approved_by   varchar(60),
    approved_at   timestamp(3),
    posted_by     varchar(60),
    posted_at     timestamp(3),
    tr_year       integer,
    tr_ctlno      bigint,
    cancel_reason varchar(200),
    CONSTRAINT ecis_opening_batch_status CHECK (status IN ('DRAFT', 'FOR_REVIEW', 'APPROVED', 'POSTED', 'CANCELLED'))
);
CREATE INDEX ecis_opening_batch_branch ON legacy.ecis_opening_batch (branch_code, status);
CREATE TABLE legacy.ecis_opening_line (
    batch_id     bigint        NOT NULL REFERENCES legacy.ecis_opening_batch (id),
    line_no      integer       NOT NULL,
    kind         varchar(10)   NOT NULL,
    client_id    integer,
    type_code    integer,
    ref_no       integer,
    account_code varchar(20),
    debit        numeric(15,2) NOT NULL,
    credit       numeric(15,2) NOT NULL,
    note         varchar(100),
    PRIMARY KEY (batch_id, line_no),
    CONSTRAINT ecis_opening_line_kind CHECK (kind IN ('GL', 'SAVINGS', 'SHARE'))
);
GRANT SELECT, INSERT, UPDATE ON legacy.ecis_opening_batch TO coop_app;
GRANT SELECT, INSERT, DELETE ON legacy.ecis_opening_line TO coop_app;
