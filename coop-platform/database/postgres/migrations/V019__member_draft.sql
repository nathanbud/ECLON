-- A new-member registration saved as a draft before it is sent for approval. Each draft belongs to the person who typed it and only they see it. It holds the typed fields only
-- (no photo, signature or fingerprints) and is deleted when the registration is sent or the draft is discarded. The MySQL copy is V056. Apply with scripts/migrate-postgres.ps1.
CREATE TABLE legacy.ecis_member_draft (
    id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    owner       varchar(60)  NOT NULL,
    branch_code integer      NOT NULL,
    client_type integer      NOT NULL,
    title       varchar(120) NOT NULL,
    fields      text         NOT NULL,
    created_at  timestamp    NOT NULL,
    updated_at  timestamp    NOT NULL
);
CREATE INDEX ecis_member_draft_owner ON legacy.ecis_member_draft (owner, updated_at);
GRANT SELECT, INSERT, UPDATE, DELETE ON legacy.ecis_member_draft TO coop_app;
