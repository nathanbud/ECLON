package ph.coop.core.loan;

import static org.junit.jupiter.api.Assertions.assertEquals;
import static org.junit.jupiter.api.Assertions.assertTrue;

import java.math.BigDecimal;
import java.time.LocalDate;
import java.time.LocalDateTime;
import java.util.List;
import net.sf.jasperreports.engine.JasperPrint;
import net.sf.jasperreports.engine.JRPrintElement;
import net.sf.jasperreports.engine.JRPrintText;
import org.junit.jupiter.api.Test;

/**
 * The printed Amortization Schedule against the cooperative's own printout (pics/amortsched.pdf: 100,000.00 at 12 % a year on a diminishing balance,
 * monthly for 10 years, released 04/24/2026). The figures below are copied from that printout; its Others column (insurance) is not charged by an application.
 */
class AmortizationSchedulePrintTest {

    private static final LocalDate RELEASE = LocalDate.of(2026, 4, 24);

    private static List<AmortizationSchedulePrint.Line> sample() {
        return AmortizationSchedulePrint.lines(LoanSchedule.diminishing(new BigDecimal("100000.00"), 120, LoanSchedule.MONTHLY, new BigDecimal("12"), RELEASE));
    }

    private static void line(AmortizationSchedulePrint.Line l, String date, String interest, String principal, String balance) {
        assertEquals(date, l.date().toString(), "date of line " + l.no());
        assertEquals(new BigDecimal(interest), l.interest(), "interest of line " + l.no());
        assertEquals(new BigDecimal(principal), l.principal(), "principal of line " + l.no());
        assertEquals(new BigDecimal(balance), l.balance(), "balance of line " + l.no());
        assertEquals(l.interest().add(l.principal()).add(l.others()), l.total(), "total of line " + l.no());
    }

    @Test
    void theLinesAreTheOnesTheOldPrintoutShows() {
        List<AmortizationSchedulePrint.Line> s = sample();
        assertEquals(121, s.size());
        line(s.get(0), "2026-04-24", "0.00", "0.00", "100000.00");
        line(s.get(1), "2026-05-24", "986.30", "833.33", "99166.67");
        line(s.get(2), "2026-06-24", "1010.68", "833.33", "98333.34");
        line(s.get(11), "2027-03-24", "843.84", "833.33", "90833.37");
        line(s.get(36), "2029-04-24", "721.92", "833.33", "70000.12");
        line(s.get(119), "2036-03-24", "15.89", "833.33", "833.73");
        line(s.get(120), "2036-04-24", "8.50", "833.73", "0.00");
        BigDecimal interest = s.stream().map(AmortizationSchedulePrint.Line::interest).reduce(BigDecimal.ZERO, BigDecimal::add);
        assertEquals(new BigDecimal("60556.39"), interest);
        assertEquals(new BigDecimal("6.06"), AmortizationSchedulePrint.effectiveRate(interest, new BigDecimal("100000.00"), 120));
    }

    @Test
    void thePrintoutHasTheHeaderEveryLineTheTotalsAndASignaturePage() throws Exception {
        List<AmortizationSchedulePrint.Line> lines = sample();
        AmortizationSchedulePrint.Sheet sheet = new AmortizationSchedulePrint.Sheet("TEST COOPERATIVE", "Main Office", "Somewhere", "000-000-000-000", "0001-0000001-1",
            "Member, Test A.", "To be assigned", "Business Loan - Medical", "Officer, Test", "New", "North", new BigDecimal("100000.00"), "Monthly",
            "10.00 Years", new BigDecimal("12"), new BigDecimal("6.06"), "Diminishing Bal", "Monthly", new BigDecimal("36"), "Monthly", RELEASE,
            lines.get(1).date(), lines.get(1).date(), lines.get(120).date(), "Office-MOA", lines);
        JasperPrint p = new AmortizationSchedulePrint(null, "", "Coop Platform").filled(sheet, "itest", LocalDateTime.of(2026, 11, 15, 14, 23));
        StringBuilder all = new StringBuilder();
        for (var page : p.getPages()) for (JRPrintElement e : page.getElements()) if (e instanceof JRPrintText t) all.append(t.getFullText()).append('\n');
        String text = all.toString();
        for (String s : List.of("AMORTIZATION SCHEDULE", "TEST COOPERATIVE", "0001-0000001-1", "To be assigned", "100,000.00", "12 % p. a.", "6.06% p.a.",
            "Diminishing Bal", "05/24/2026", "04/24/2036", "986.30", "99,166.67", "160,556.39", "60,556.39", "CONFORME:", "Signature Over Printed Name",
            "This is a System Generated Document.", "Generated by: itest", "Date Created: November 15, 2026")) {
            assertTrue(text.contains(s), "the printout shows " + s);
        }
        assertTrue(p.getPages().size() >= 4, "120 lines take three pages and the signature has its own: " + p.getPages().size());
        byte[] pdf = new AmortizationSchedulePrint(null, "", "Coop Platform").pdf(sheet, "itest", LocalDateTime.now());
        assertEquals("%PDF", new String(pdf, 0, 4));
        String out = System.getProperty("amortization.out"); // to look at the layout: -Damortization.out=some.pdf
        if (out != null) java.nio.file.Files.write(java.nio.file.Path.of(out), pdf);
    }
}
