package ph.coop.core.connection;

import static org.junit.jupiter.api.Assertions.assertEquals;
import static org.junit.jupiter.api.Assertions.assertTrue;

import java.util.LinkedHashMap;
import java.util.List;
import java.util.Map;
import org.junit.jupiter.api.Test;

/** The comparison of the build's database changes with a database's log. Pure, no database. */
class SchemaRulesTest {

    private static Map<String, String[]> build(int from, int to) {
        Map<String, String[]> m = new LinkedHashMap<>();
        for (int i = from; i <= to; i++) m.put(String.format("V%03d", i), new String[]{String.format("V%03d__change.sql", i), "SUM" + i});
        return m;
    }

    private static Map<String, SchemaRules.Recorded> log(int from, int to) {
        Map<String, SchemaRules.Recorded> m = new LinkedHashMap<>();
        for (int i = from; i <= to; i++) m.put(String.format("V%03d", i), new SchemaRules.Recorded("SUM" + i, "APPLIED"));
        return m;
    }

    @Test void aDatabaseWithEveryChangeIsUpToDate() {
        var r = SchemaRules.compare(build(1, 33), log(1, 33));
        assertEquals(SchemaRules.State.UP_TO_DATE, r.state());
        assertEquals("V033", r.lastExpected());
        assertTrue(SchemaRules.message(r, "coop").contains("up to V033"));
    }

    @Test void missingChangesAreNamedInOrder() {
        var r = SchemaRules.compare(build(1, 33), log(1, 30));
        assertEquals(SchemaRules.State.BEHIND, r.state());
        assertEquals(List.of("V031 V031__change.sql", "V032 V032__change.sql", "V033 V033__change.sql"), r.missing());
        assertTrue(SchemaRules.message(r, "coop_bgempc").contains("is missing 3 database changes"));
        assertTrue(SchemaRules.message(r, "coop_bgempc").contains("V031, V032, V033"));
    }

    @Test void changesBeforeTheLogStartedAreTakenAsApplied() {
        // coop_bgempc: V001 to V019 were applied before its log existed; its log starts at V020
        var r = SchemaRules.compare(build(1, 33), log(20, 33));
        assertEquals(SchemaRules.State.UP_TO_DATE, r.state());
        // but a gap after the log started is still missing
        var gap = log(20, 33);
        gap.remove("V025");
        assertEquals(List.of("V025 V025__change.sql"), SchemaRules.compare(build(1, 33), gap).missing());
    }

    @Test void aDatabaseUpdatedByANewerVersionSaysSo() {
        var r = SchemaRules.compare(build(1, 33), log(1, 35));
        assertEquals(SchemaRules.State.NEWER, r.state());
        assertEquals(List.of("V034", "V035"), r.newer());
    }

    @Test void anEditedChangeIsReportedButNotMissing() {
        var recorded = log(1, 33);
        recorded.put("V030", new SchemaRules.Recorded("OTHER", "APPLIED"));
        recorded.put("V010", new SchemaRules.Recorded("OTHER", "APPLIED")); // regenerated by the setup script: not compared
        recorded.put("V005", new SchemaRules.Recorded("OTHER", "BASELINE")); // baseline rows carry no real fingerprint
        var r = SchemaRules.compare(build(1, 33), recorded);
        assertEquals(SchemaRules.State.UP_TO_DATE, r.state());
        assertEquals(List.of("V030 V030__change.sql"), r.changed());
    }

    @Test void fingerprintsAreComparedWhateverTheirCase() {
        var recorded = log(1, 3);
        recorded.put("V002", new SchemaRules.Recorded("sum2", "APPLIED"));
        assertTrue(SchemaRules.compare(build(1, 3), recorded).changed().isEmpty());
    }

    @Test void noLogMeansEverythingIsUnknown() {
        var r = SchemaRules.compare(build(1, 3), null);
        assertEquals(SchemaRules.State.NO_LOG, r.state());
        assertEquals(3, r.missing().size());
        var empty = SchemaRules.compare(build(1, 3), new LinkedHashMap<>());
        assertEquals(SchemaRules.State.BEHIND, empty.state());
        assertEquals(3, empty.missing().size());
    }
}
